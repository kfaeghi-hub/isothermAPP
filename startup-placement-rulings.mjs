// 678 occurrences collapse to 289 DISTINCT labels; a label is ruled once and
// the ruling applies to every occurrence. Each carries a confidence class:
//
//   high    — the wording settles it. No reading required.
//   medium  — reasoned and defensible; a glance is enough.
//   low     — GENUINELY UNCERTAIN. These go to the owner by name.
//   cut     — not a checkable thing: a banner, a furniture leak, a label with
//             no verb. Cut rather than placed.
//
// PLACEMENT TEST — what does the check physically require?
//   A  the unit can be dead. Installation, condition, documents, prerequisites.
//   B  an ordered step in energizing or first-starting. The order is the content.
//   C  the unit must be RUNNING. Behaviour, modulation, continuous operation.
//   D  a protective device PROVEN — tripped, simulated, or its interlock fired.
//   E  a quantity RECORDED, with units.
//
// Two clusters were web-verified rather than guessed:
//   · NETA ATS separates "Visual and Mechanical Inspection" from "Electrical
//     Tests", both performed before initial energization. So transformer and
//     switchgear INSPECTION rows are A, and "All Specified Tests – Data
//     Recorded" is E. https://blog.ansi.org/ansi/ansi-neta-ats-2025-electrical-power-testing/
//   · NFPA 13 dry-pipe air-pressure tests (40 psi / 24 h / <1.5 psi loss) are
//     ACCEPTANCE tests completed before the system is in service, so a
//     pressure-loss row is a pre-start result (A) and the pressure itself is a
//     reading (E). https://www.cityofmobile.org/fire/docs/sprinkler-system-nfpa-13---acceptance-inspection.pdf
//
